"""Writes docs/reference/cli.md from the help of the `ooa` command itself.

Usage: python make-cli-reference.py <path to ooa or ooa.bat> <out.md>
Asks `ooa --help`, then `ooa COMMAND --help` for every command and sub-command it lists, and puts the help texts on
one page with a contents list. Run it again after commands change.
"""
import os
import re
import subprocess
import sys


# colour codes in the help text (ESC [ ... m)
ANSI = re.compile(chr(27) + r"\[[0-9;]*m")


def help_of(ooa, words):
    env = dict(os.environ, NO_COLOR="1", JAVA_OPTS="-Dpicocli.ansi=false")
    r = subprocess.run([ooa] + words + ["--help"], capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=120, env=env)
    return ANSI.sub("", r.stdout or r.stderr).rstrip()


def subcommands(text):
    out, inside = [], False
    for line in text.splitlines():
        if line.strip() == "Commands:":
            inside = True
            continue
        if inside:
            if not line.strip() or not line.startswith("  "):
                if out and not line.strip():
                    break
                continue
            m = re.match(r"^  ([a-z][a-z0-9-]*)\s", line + " ")
            if m and not line.startswith("    "):
                out.append(m.group(1))
    return out


def main(ooa, out):
    top = help_of(ooa, [])
    sections, todo = [], [[c] for c in subcommands(top)]
    while todo:
        words = todo.pop(0)
        if words[-1] in ("help", "service-run", "native-host") or len(words) > 3 or len(set(words)) < len(words):
            continue
        text = help_of(ooa, words)
        sections.append((words, text))
        todo[0:0] = [words + [s] for s in subcommands(text)]
    lines = ["# Command-line reference (`ooa`)", "",
             "Every command and sub-command of the `ooa` program, with its options, as the program's own help prints them.",
             "Generated by `docs/research/tools/make-cli-reference.py`; do not edit by hand. On Windows the program is",
             "`bin\\ooa.bat` in the installation folder; on Linux `bin/ooa`.", "",
             "`service-run` and `native-host` are started by Windows and by the browser, not by people, and are left out.", "",
             "## Contents", ""]
    for words, _ in sections:
        anchor = "ooa-" + "-".join(words)
        lines.append("  " * (len(words) - 1) + "- [ooa " + " ".join(words) + "](#" + anchor + ")")
    lines += ["", "## ooa", "", "```text", top, "```", ""]
    for words, text in sections:
        lines += ["#" * min(2 + len(words) - 1, 4) + " ooa " + " ".join(words), "", "```text", text, "```", ""]
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(len(sections), "commands")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
