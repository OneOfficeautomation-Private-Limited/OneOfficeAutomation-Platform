"""Writes platform/ui/src/studio/aaNames.ts from docs/research/command-comparison.data.json (aaMap: "AA package/AA
action" -> "our toolkit/our action"), so the action library finds a command by the name people know from AA.
Run in the repository root: python -I docs/research/tools/make-aa-names.py"""
import json

d = json.load(open("docs/research/command-comparison.data.json", encoding="utf-8"))
names = {}
for aa, ours in d["aaMap"].items():
    if not ours:
        continue
    pkg, _, action = aa.partition("/")
    label = action + " (" + pkg + ")" if action and action != pkg else pkg
    names.setdefault(ours, [])
    if label not in names[ours]:
        names[ours].append(label)

lines = [
    "// Generated by the usage review (item 26, 9 Nov 2026) from docs/research/command-comparison.data.json; do not edit by hand.",
    "// AA's command names for each of our actions, so the action library finds a command by the name people know from AA.",
    "export const AA_NAMES: Record<string, string[]> = {",
]
for ours in sorted(names):
    lines.append("  " + json.dumps(ours) + ": " + json.dumps(sorted(names[ours]), ensure_ascii=False) + ",")
lines.append("};")
open("platform/ui/src/studio/aaNames.ts", "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print(len(names), "actions with AA names")
